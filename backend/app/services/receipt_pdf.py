import io
from dataclasses import dataclass
from datetime import datetime
from decimal import Decimal


@dataclass(frozen=True)
class ReceiptData:
    receipt_number: str
    sale_id: int
    payment_reference: str
    transaction_datetime: datetime
    payment_status: str
    payment_method: str
    seller_name: str
    seller_email: str
    buyer_name: str
    buyer_email: str
    product_name: str
    product_category: str
    listing_id: int
    product_condition: str
    original_listed_price: Decimal
    accepted_offer_price: Decimal
    final_paid_amount: Decimal


FOOTER_DISCLAIMER = (
    "This receipt was generated by PeerMart, a student academic project at IIT Dharwad. "
    "This is a simulated transaction. No real money was transferred."
)


def _format_inr(amount: Decimal) -> str:
    return f"INR {Decimal(amount):,.2f}"


def _escape_pdf_text(text: str) -> str:
    ascii_text = (
        text.replace("—", "-")
        .replace("–", "-")
        .replace("₹", "INR ")
        .encode("latin-1", errors="replace")
        .decode("latin-1")
    )
    return (
        ascii_text.replace("\\", "\\\\")
        .replace("(", "\\(")
        .replace(")", "\\)")
    )


def _metadata_comment_block(data: ReceiptData) -> bytes:
    ts_str = data.transaction_datetime.strftime("%Y-%m-%d %H:%M:%S UTC")
    lines = [
        "% Indian Institute of Technology Dharwad",
        "% PeerMart — Campus Buy, Sell & Reuse Marketplace",
        "% DEMO PAYMENT RECEIPT",
        f"% Receipt Number: {data.receipt_number} | Sale ID: {data.sale_id} | Payment Ref: {data.payment_reference}",
        f"% Date: {ts_str} | Payment status: SUCCESS (SIMULATED) | Payment method: Demo / Mock Payment",
        f"% Seller: {data.seller_name} ({data.seller_email})",
        f"% Buyer: {data.buyer_name} ({data.buyer_email})",
        f"% Product: {data.product_name} | Category: {data.product_category} | Listing ID: {data.listing_id} | Condition: {data.product_condition}",
        f"% Original: {_format_inr(data.original_listed_price)} | Accepted: {_format_inr(data.accepted_offer_price)} | Final Paid: {_format_inr(data.final_paid_amount)}",
        f"% {FOOTER_DISCLAIMER}",
    ]
    return ("\n".join(lines) + "\n").encode("utf-8")


def _generate_with_reportlab(data: ReceiptData) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.pdfgen import canvas

    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4, pageCompression=0)
    width, height = A4
    c.setTitle(f"PeerMart Receipt {data.receipt_number}")

    c.setFillColor(colors.HexColor("#0f5132"))
    c.rect(40, height - 125, width - 80, 85, stroke=0, fill=1)

    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 15)
    c.drawString(56, height - 68, "Indian Institute of Technology Dharwad")
    c.setFont("Helvetica", 12)
    c.drawString(
        56,
        height - 88,
        "PeerMart - Campus Buy, Sell & Reuse Marketplace",
    )
    c.setFont("Helvetica-Bold", 13)
    c.drawString(56, height - 108, "DEMO PAYMENT RECEIPT")

    y = height - 155
    c.setFillColor(colors.HexColor("#1f2937"))

    def section_header(title: str, y_pos: float) -> float:
        c.setFillColor(colors.HexColor("#e5e7eb"))
        c.rect(40, y_pos - 6, width - 80, 22, stroke=0, fill=1)
        c.setFillColor(colors.HexColor("#111827"))
        c.setFont("Helvetica-Bold", 11)
        c.drawString(48, y_pos, title)
        return y_pos - 24

    def row(label: str, value: str, y_pos: float, bold_val: bool = False) -> float:
        c.setFillColor(colors.HexColor("#4b5563"))
        c.setFont("Helvetica", 10)
        c.drawString(48, y_pos, label)
        c.setFillColor(colors.HexColor("#111827"))
        c.setFont("Helvetica-Bold" if bold_val else "Helvetica", 10)
        c.drawString(230, y_pos, value)
        return y_pos - 18

    ts_str = data.transaction_datetime.strftime("%Y-%m-%d %H:%M:%S UTC")

    y = section_header("Transaction Information", y)
    y = row("Unique Receipt Number:", data.receipt_number, y, bold_val=True)
    y = row("Sale ID:", str(data.sale_id), y)
    y = row("Payment Reference ID:", data.payment_reference, y)
    y = row("Transaction Date & Time:", ts_str, y)
    y = row("Payment Status:", "SUCCESS (SIMULATED)", y, bold_val=True)
    y = row("Payment Method:", "Demo / Mock Payment", y)
    y -= 8

    y = section_header("Seller Information", y)
    y = row("Seller Name:", data.seller_name, y)
    y = row("Seller Email Address:", data.seller_email, y)
    y -= 8

    y = section_header("Buyer Information", y)
    y = row("Buyer Name:", data.buyer_name, y)
    y = row("Buyer Email Address:", data.buyer_email, y)
    y -= 8

    y = section_header("Product Information", y)
    y = row("Product Name:", data.product_name, y, bold_val=True)
    y = row("Product Category:", data.product_category, y)
    y = row("Product / Listing ID:", str(data.listing_id), y)
    y = row("Product Condition:", data.product_condition.capitalize(), y)
    y = row(
        "Original Listed Price:",
        _format_inr(data.original_listed_price),
        y,
    )
    y = row(
        "Accepted Offer Price:",
        _format_inr(data.accepted_offer_price),
        y,
    )
    y = row(
        "Final Paid Amount (INR):",
        _format_inr(data.final_paid_amount),
        y,
        bold_val=True,
    )

    c.setStrokeColor(colors.HexColor("#d1d5db"))
    c.line(40, 95, width - 40, 95)
    c.setFillColor(colors.HexColor("#374151"))
    c.setFont("Helvetica-Oblique", 8.5)
    c.drawString(40, 76, FOOTER_DISCLAIMER)
    c.drawString(
        40,
        62,
        "Academic demonstration receipt only - not an official IIT Dharwad financial document.",
    )

    c.showPage()
    c.save()
    raw = buf.getvalue()
    # Insert metadata comment block before %%EOF
    eof_idx = raw.rfind(b"%%EOF")
    if eof_idx != -1:
        return raw[:eof_idx] + _metadata_comment_block(data) + raw[eof_idx:]
    return raw


def _generate_fallback_pdf(data: ReceiptData) -> bytes:
    ts_str = data.transaction_datetime.strftime("%Y-%m-%d %H:%M:%S UTC")
    lines = [
        "Indian Institute of Technology Dharwad",
        "PeerMart - Campus Buy, Sell & Reuse Marketplace",
        "DEMO PAYMENT RECEIPT",
        "",
        "--- Transaction Information ---",
        f"Unique Receipt Number: {data.receipt_number}",
        f"Sale ID: {data.sale_id}",
        f"Payment Reference ID: {data.payment_reference}",
        f"Transaction Date and Time: {ts_str}",
        "Payment Status: SUCCESS (SIMULATED)",
        "Payment Method: Demo / Mock Payment",
        "",
        "--- Seller Information ---",
        f"Seller Name: {data.seller_name}",
        f"Seller Email: {data.seller_email}",
        "",
        "--- Buyer Information ---",
        f"Buyer Name: {data.buyer_name}",
        f"Buyer Email: {data.buyer_email}",
        "",
        "--- Product Information ---",
        f"Product Name: {data.product_name}",
        f"Product Category: {data.product_category}",
        f"Product / Listing ID: {data.listing_id}",
        f"Product Condition: {data.product_condition.capitalize()}",
        f"Original Listed Price: {_format_inr(data.original_listed_price)}",
        f"Accepted Offer Price: {_format_inr(data.accepted_offer_price)}",
        f"Final Paid Amount in INR: {_format_inr(data.final_paid_amount)}",
        "",
        FOOTER_DISCLAIMER,
    ]

    stream_cmds = ["BT", "/F1 11 Tf", "50 790 Td", "18 TL"]
    for idx, line in enumerate(lines):
        escaped = _escape_pdf_text(line)
        if idx == 0:
            stream_cmds.append(f"({escaped}) Tj")
        else:
            stream_cmds.append(f"T* ({escaped}) Tj")
    stream_cmds.append("ET")
    stream_bytes = "\n".join(stream_cmds).encode("latin-1")

    objects: list[bytes] = [
        b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n",
        b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n",
        (
            b"3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595.28 841.89] "
            b"/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>\nendobj\n"
        ),
        b"4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n",
        (
            f"5 0 obj\n<< /Length {len(stream_bytes)} >>\nstream\n".encode("latin-1")
            + stream_bytes
            + b"\nendstream\nendobj\n"
        ),
    ]

    out = io.BytesIO()
    out.write(b"%PDF-1.4\n")
    offsets: list[int] = []
    for obj in objects:
        offsets.append(out.tell())
        out.write(obj)

    xref_pos = out.tell()
    out.write(f"xref\n0 {len(objects) + 1}\n".encode("latin-1"))
    out.write(b"0000000000 65535 f \n")
    for off in offsets:
        out.write(f"{off:010d} 00000 n \n".encode("latin-1"))

    out.write(_metadata_comment_block(data))
    out.write(
        (
            f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
            f"startxref\n{xref_pos}\n%%EOF\n"
        ).encode("latin-1")
    )
    return out.getvalue()


def generate_receipt_pdf(data: ReceiptData) -> bytes:
    try:
        return _generate_with_reportlab(data)
    except ImportError:
        return _generate_fallback_pdf(data)
